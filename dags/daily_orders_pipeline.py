"""Daily orders ETL pipeline.

Schedule: daily, catchup off (a missed day backfills on demand, never by
surprise). Chain: extract -> validate -> transform (TaskGroup) -> load ->
notify. Validation is a task in the DAG, so a rule failure blocks the
load and triggers Airflow's retry instead of letting bad data through.

Stages communicate through files under ``data/`` (not through XCom row
payloads): each task reads the previous stage's file and writes its own,
and the load overwrites the day's warehouse partition, so a re-run for
the same date is idempotent. XCom carries only counts/metrics. The
stage logic lives in ``src/pipeline.py`` / ``src/transform.py`` and is
shared with the local runner, so the code exercised locally is the code
Airflow runs.

Local demo note: the extract reads the single synthetic source file
``data/orders.csv`` (generated by ``python -m src.generate_data``). In
a real deployment it would pull the run date's partition from the
source system; the staging, validation, transform, and load steps are
already date-partitioned by the run date in their file handling.
"""

from __future__ import annotations

import logging
import sys
from datetime import timedelta
from pathlib import Path

from airflow import DAG
from airflow.operators.python import PythonOperator
from airflow.utils.task_group import TaskGroup

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from common import START_DATE, TAGS, default_args_for, on_failure  # noqa: E402
from operators.data_quality_operator import DataQualityOperator  # noqa: E402
from src.config import load_config  # noqa: E402
from src.pipeline import stage_extract, stage_validate  # noqa: E402
from src.schema import ORDER_COLUMNS, WAREHOUSE_COLUMNS  # noqa: E402
from src.storage import read_csv, write_csv_atomic  # noqa: E402
from src.transform import clean_rows, enrich_rows, model_rows  # noqa: E402

logger = logging.getLogger(__name__)

CONFIG = load_config()
DAG_ID = "daily_orders_pipeline"
DATA_DIR = PROJECT_ROOT / "data"
SOURCE_PATH = DATA_DIR / "orders.csv"

# One file per stage, so each task's input/output is inspectable and a
# failed task can be re-run without re-running the whole chain.
STAGING_FILE = "staging_orders.csv"
CLEAN_FILE = "clean_orders.csv"
ENRICHED_FILE = "enriched_orders.csv"
MODELED_FILE = "modeled_orders.csv"
WAREHOUSE_FILE = "warehouse_orders.csv"
QUARANTINE_FILE = "quarantine.csv"


def _stage_path(filename: str) -> Path:
    return DATA_DIR / filename


def extract(ds: str, **context: object) -> dict:
    """Pull the day's raw order records into staging."""
    rows = stage_extract(SOURCE_PATH, _stage_path(STAGING_FILE))
    logger.info("extract: %d raw records staged for %s", len(rows), ds)
    return {"staged_records": len(rows), "partition": ds}


def clean(ds: str, **context: object) -> dict:
    """Drop rows the validator marked bad; quarantine them for review."""
    rows = read_csv(_stage_path(STAGING_FILE))
    result = stage_validate(rows, CONFIG.data_quality)
    cleaned = clean_rows(rows, result.bad_indices)
    quarantined = [row for i, row in enumerate(rows) if i in result.bad_indices]
    write_csv_atomic(_stage_path(CLEAN_FILE), cleaned, ORDER_COLUMNS)
    quarantine_path = _stage_path(QUARANTINE_FILE)
    if quarantined:
        write_csv_atomic(quarantine_path, quarantined, ORDER_COLUMNS)
    elif quarantine_path.exists():
        # No rejects this run: remove a stale file so it cannot be
        # mistaken for this run's quarantined rows.
        quarantine_path.unlink()
    logger.info(
        "transform.clean: %d clean, %d quarantined for %s",
        len(cleaned),
        len(quarantined),
        ds,
    )
    return {"clean_records": len(cleaned), "rejected": result.rows_rejected}


def enrich(ds: str, **context: object) -> dict:
    """Normalise fields and derive reporting fields."""
    rows = read_csv(_stage_path(CLEAN_FILE))
    enriched = enrich_rows(rows)
    fieldnames = list(enriched[0].keys()) if enriched else list(ORDER_COLUMNS) + ["amount_usd"]
    write_csv_atomic(_stage_path(ENRICHED_FILE), enriched, fieldnames)
    logger.info("transform.enrich: %d records enriched for %s", len(enriched), ds)
    return {"enriched_records": len(enriched)}


def model(ds: str, **context: object) -> dict:
    """Shape records into the warehouse model."""
    rows = read_csv(_stage_path(ENRICHED_FILE))
    modeled = model_rows(rows)
    write_csv_atomic(_stage_path(MODELED_FILE), modeled, WAREHOUSE_COLUMNS)
    logger.info("transform.model: %d records modeled for %s", len(modeled), ds)
    return {"modeled_records": len(modeled)}


def load(ds: str, **context: object) -> dict:
    """Write the clean records to the warehouse, replacing the partition."""
    rows = read_csv(_stage_path(MODELED_FILE))
    written = write_csv_atomic(_stage_path(WAREHOUSE_FILE), rows, WAREHOUSE_COLUMNS)
    logger.info("load: %d records written to warehouse/orders (%s)", written, ds)
    return {"loaded_records": written, "partition": ds}


def notify(**context: object) -> dict:
    """Log the outcome; failures reach on-call via on_failure_callback."""
    ti = context["ti"]
    loaded = ti.xcom_pull(task_ids="load") or {}
    count = loaded.get("loaded_records", 0) if isinstance(loaded, dict) else 0
    logger.info("notify: %s succeeded, %d rows loaded", DAG_ID, count)
    return {"loaded_records": count}


with DAG(
    dag_id=DAG_ID,
    default_args={**default_args_for(DAG_ID), "on_failure_callback": on_failure},
    description="Daily orders ETL: extract, validate, transform, load",
    schedule=timedelta(days=1),
    start_date=START_DATE,
    catchup=False,
    max_active_runs=1,
    tags=TAGS,
) as dag:

    extract_task = PythonOperator(
        task_id="extract",
        python_callable=extract,
    )

    validate_task = DataQualityOperator(
        task_id="validate",
        dataset="data/staging_orders.csv",
        rules=CONFIG.data_quality.to_dict(),
    )

    with TaskGroup(group_id="transform") as transform_group:
        clean_task = PythonOperator(task_id="clean", python_callable=clean)
        enrich_task = PythonOperator(task_id="enrich", python_callable=enrich)
        model_task = PythonOperator(task_id="model", python_callable=model)
        clean_task >> enrich_task >> model_task

    load_task = PythonOperator(
        task_id="load",
        python_callable=load,
    )

    notify_task = PythonOperator(
        task_id="notify",
        python_callable=notify,
        trigger_rule="all_success",
    )

    extract_task >> validate_task >> transform_group >> load_task >> notify_task
